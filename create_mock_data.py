import requests
import json

urls = {
    'topology': 'http://127.0.0.1:8001/api/datasets/Market-1501/camera-topology',
    'benchmarks': 'http://127.0.0.1:8001/api/experiments/benchmark-data',
    'samples': 'http://127.0.0.1:8001/api/retrieval/samples',
    'demo': 'http://127.0.0.1:8001/api/inference/precomputed-demo'
}

data = {}
for k, url in urls.items():
    try:
        r = requests.get(url, timeout=5)
        if r.status_code == 200:
            data[k] = r.json()
    except Exception as e:
        print(f'Failed {k}:', e)

# Also get a sample search result
if 'samples' in data and len(data['samples']) > 0:
    try:
        s_res = requests.post(
            'http://127.0.0.1:8001/api/retrieval/search',
            json={'query_filename': data['samples'][0]['filename'], 'top_k': 10},
            timeout=5
        )
        if s_res.status_code == 200:
            data['search_sample'] = s_res.json()
    except Exception as e:
        print('Failed search sample:', e)

with open('frontend/src/lib/mockData.ts', 'w', encoding='utf-8') as f:
    f.write('// Autogenerated fallback data for cloud deployments (Vercel)\n\n')
    f.write('export const MOCK_TOPOLOGY: any = ' + json.dumps(data.get('topology', {}), indent=2) + ';\n\n')
    f.write('export const MOCK_BENCHMARKS: any = ' + json.dumps(data.get('benchmarks', {}), indent=2) + ';\n\n')
    f.write('export const MOCK_SAMPLES: any[] = ' + json.dumps(data.get('samples', [])[:16], indent=2) + ';\n\n')
    f.write('export const MOCK_SEARCH: any = ' + json.dumps(data.get('search_sample', {}), indent=2) + ';\n\n')
    f.write('export const MOCK_DEMO: any = ' + json.dumps(data.get('demo', {}), indent=2) + ';\n\n')

print('Wrote frontend/src/lib/mockData.ts successfully!')
